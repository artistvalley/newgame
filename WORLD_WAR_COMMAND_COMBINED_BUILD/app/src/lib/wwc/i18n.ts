export type CopyKey = keyof typeof COPY.en;

export function t(lang: string, key: CopyKey): string {
  if (lang === "ta" || lang === "hi") {
    const local = (COPY[lang] as Partial<Record<CopyKey, string>>)[key];
    if (local) return local;
  }
  return COPY.en[key];
}

